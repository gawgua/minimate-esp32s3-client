#!/usr/bin/env python3
"""Scale the 128x128 face animations to the 128x64 SSD1306 and emit page-layout frames.

Reads the generated face_animations.h (not the generator) so the OLED shows exactly the
shipped artwork. Requires numpy and Pillow on the host.

    python tools/make_oled_faces.py                       # ~/face_animations/face_animations.h
    python tools/make_oled_faces.py path/to/face_animations.h --preview faces.png
"""

import argparse
import re
from pathlib import Path

import numpy as np
from PIL import Image

SRC_SIZE = 128
WIDTH, HEIGHT = 128, 64
# Leave the bottom rows free for the sketch's recording progress bar.
FACE_ROWS = 62
STATES = ("idle", "listening", "processing", "speaking", "clarification", "error")
FRAMES = 15
# Coverage needed to light a pixel. Below 0.5 so 2 px strokes survive the ~0.7x scale.
THRESHOLD = 0.35
OUTPUT = Path(__file__).resolve().parents[1] / "face_frames_128x64.h"


def decode(header: Path) -> np.ndarray:
    words = [int(v, 16) for v in re.findall(r"UINT64_C\(0x([0-9A-Fa-f]{16})\)", header.read_text())]
    expected = len(STATES) * FRAMES * SRC_SIZE * 2
    if len(words) != expected:
        raise SystemExit(f"Expected {expected} words in {header}, found {len(words)}")
    bits = np.array(words, dtype=np.uint64).reshape(len(STATES) * FRAMES, SRC_SIZE, 2, 1)
    shifts = np.arange(63, -1, -1, dtype=np.uint64)
    pixels = (bits >> shifts) & np.uint64(1)
    return pixels.reshape(len(STATES), FRAMES, SRC_SIZE, SRC_SIZE).astype(bool)


def scale(frames: np.ndarray) -> np.ndarray:
    # One crop for every frame so the face does not jump when the state changes.
    lit = frames.any(axis=(0, 1))
    rows, cols = np.flatnonzero(lit.any(axis=1)), np.flatnonzero(lit.any(axis=0))
    top, bottom, left, right = rows[0], rows[-1] + 1, cols[0], cols[-1] + 1
    factor = min(FACE_ROWS / (bottom - top), WIDTH / (right - left))
    size = (round((right - left) * factor), round((bottom - top) * factor))
    x0, y0 = (WIDTH - size[0]) // 2, (FACE_ROWS - size[1]) // 2
    out = np.zeros((*frames.shape[:2], HEIGHT, WIDTH), dtype=bool)
    for state in range(frames.shape[0]):
        for frame in range(frames.shape[1]):
            crop = frames[state, frame, top:bottom, left:right].astype(np.uint8) * 255
            # BOX averages source coverage, so thin lines become gray instead of vanishing.
            small = Image.fromarray(crop, "L").resize(size, Image.Resampling.BOX)
            region = np.asarray(small) >= THRESHOLD * 255
            out[state, frame, y0 : y0 + size[1], x0 : x0 + size[0]] = region
    print(f"Crop {right - left}x{bottom - top} at ({left},{top}), scale {factor:.3f} -> {size}")
    return out


def to_pages(image: np.ndarray) -> bytes:
    """SSD1306 layout: 8 pages of 128 bytes, each byte a column of 8 pixels, LSB on top."""
    pages = image.reshape(HEIGHT // 8, 8, WIDTH)
    weights = (1 << np.arange(8)).reshape(1, 8, 1)
    return (pages * weights).sum(axis=1).astype(np.uint8).tobytes()


def write_header(images: np.ndarray, path: Path):
    lines = [
        "// Generated by tools/make_oled_faces.py from face_animations.h. Do not edit.",
        "// 128x64 SSD1306 page layout: face_oled_frames[state][frame] is 1024 bytes,",
        "// 8 pages x 128 columns, LSB = top pixel. memcpy into Adafruit_SSD1306::getBuffer().",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        f"constexpr uint8_t FACE_OLED_FPS = {FRAMES};  // Every state loops once per second.",
        f"constexpr uint8_t FACE_OLED_FRAMES = {FRAMES};",
        f"constexpr uint8_t FACE_OLED_FACE_ROWS = {FACE_ROWS};",
        "",
        "enum class Face : uint8_t {",
        *(f"  {name.title()}," for name in STATES),
        "  Count,",
        "};",
        "",
        (
            "const uint8_t face_oled_frames[static_cast<int>(Face::Count)]"
            f"[FACE_OLED_FRAMES][{WIDTH * HEIGHT // 8}] = {{"
        ),
    ]
    for name, frames in zip(STATES, images):
        lines.append(f"  {{  // {name}")
        for index, image in enumerate(frames):
            data = to_pages(image)
            lines.append(f"    {{  // frame {index}")
            for start in range(0, len(data), 16):
                lines.append(
                    "      " + ", ".join(f"0x{b:02X}" for b in data[start : start + 16]) + ","
                )
            lines.append("    },")
        lines.append("  },")
    lines += ["};", ""]
    path.write_text("\n".join(lines))


def write_preview(images: np.ndarray, path: Path, zoom: int = 3):
    gap = 4
    sheet = np.zeros((len(STATES) * (HEIGHT + gap), FRAMES * (WIDTH + gap)), dtype=np.uint8)
    for s, frames in enumerate(images):
        for f, image in enumerate(frames):
            y, x = s * (HEIGHT + gap), f * (WIDTH + gap)
            sheet[y : y + HEIGHT, x : x + WIDTH] = np.where(image, 255, 40)
    Image.fromarray(sheet, "L").resize(
        (sheet.shape[1] * zoom, sheet.shape[0] * zoom), Image.Resampling.NEAREST
    ).save(path)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "header", type=Path, nargs="?", default=Path("~/face_animations/face_animations.h")
    )
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument("--preview", type=Path, help="Write a PNG contact sheet of all frames")
    args = parser.parse_args()
    images = scale(decode(args.header.expanduser()))
    for state, frames in zip(STATES, images):
        if not all(frame.any() for frame in frames):
            raise SystemExit(f"A {state} frame became blank after scaling")
    write_header(images, args.output)
    print(f"Wrote {args.output} ({images.size // 8} bytes of frames)")
    if args.preview:
        write_preview(images, args.preview)
        print(f"Wrote {args.preview}")


if __name__ == "__main__":
    main()
